-- TB_ARKIVE_RACA.NM_RACA: Nome da raca.
-- TB_ARKIVE_RACA.ID_ESPECIE: Especie da raca.
-- TB_ARKIVE_RACA.TP_PORTE: Porte predominante da raca.
-- TB_ARKIVE_RACA.ST_ATIVO: Indica exclusao logica da raca: S = ativo, N = inativo.

