    NM_ESPECIE VARCHAR(50) NOT NULL,
    ST_ATIVO CHAR(1) NOT NULL DEFAULT 'S',

    CONSTRAINT PK_ARKIVE_ESPECIE PRIMARY KEY (ID_ESPECIE),
    CONSTRAINT UQ_ARKIVE_ESPECIE_NOME UNIQUE (NM_ESPECIE),
    CONSTRAINT CK_ARKIVE_ESPECIE_ATIVO CHECK (ST_ATIVO IN ('S', 'N'))
);
-- TB_ARKIVE_ESPECIE: Catalogo de especies animais.
-- TB_ARKIVE_ESPECIE.ID_ESPECIE: Identificador unico da especie.
-- TB_ARKIVE_ESPECIE.NM_ESPECIE: Nome da especie, como Cao, Gato ou Ave.
-- TB_ARKIVE_ESPECIE.ST_ATIVO: Indica exclusao logica da especie: S = ativo, N = inativo.

