CREATE TABLE TB_ARKIVE_USUARIO (
    ID_USUARIO BIGINT IDENTITY(1,1) NOT NULL,
    TP_USUARIO VARCHAR(20) NOT NULL,
    ID_RESPONSAVEL BIGINT NULL,
    ID_VETERINARIO BIGINT NULL,
    DS_LOGIN VARCHAR(200) NOT NULL,
    DS_SENHA_HASH VARCHAR(255) NOT NULL,
    DT_CADASTRO DATETIME2 NOT NULL DEFAULT GETDATE(),
    ST_ATIVO CHAR(1) NOT NULL DEFAULT 'S',

    CONSTRAINT PK_ARKIVE_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_ARKIVE_USUARIO_LOGIN UNIQUE (DS_LOGIN),
    CONSTRAINT CK_ARKIVE_USUARIO_TIPO CHECK (TP_USUARIO IN ('RESPONSAVEL', 'VETERINARIO')),
    CONSTRAINT CK_ARKIVE_USUARIO_ATIVO CHECK (ST_ATIVO IN ('S', 'N')),
    CONSTRAINT CK_ARKIVE_USUARIO_REF CHECK (
        (TP_USUARIO = 'RESPONSAVEL' AND ID_RESPONSAVEL IS NOT NULL AND ID_VETERINARIO IS NULL)
        OR
        (TP_USUARIO = 'VETERINARIO' AND ID_VETERINARIO IS NOT NULL AND ID_RESPONSAVEL IS NULL)
    ),
    CONSTRAINT FK_USUARIO_RESP FOREIGN KEY (ID_RESPONSAVEL)
        REFERENCES TB_ARKIVE_RESPONSAVEL (ID_RESPONSAVEL),
    CONSTRAINT FK_USUARIO_VET FOREIGN KEY (ID_VETERINARIO)
        REFERENCES TB_ARKIVE_VETERINARIO (ID_VETERINARIO)
);

-- ID_RESPONSAVEL and ID_VETERINARIO are nullable optional 1:1 links (most rows have one
-- of them NULL). Unlike Oracle, a plain SQL Server UNIQUE constraint/index tolerates only
-- ONE NULL per table, which would break on the second such row. Filtered unique indexes
-- (unique only where the value is present) reproduce Oracle's "NULLs are not compared" behavior.
CREATE UNIQUE INDEX UQ_ARKIVE_USUARIO_RESP ON TB_ARKIVE_USUARIO (ID_RESPONSAVEL)
    WHERE ID_RESPONSAVEL IS NOT NULL;
CREATE UNIQUE INDEX UQ_ARKIVE_USUARIO_VET ON TB_ARKIVE_USUARIO (ID_VETERINARIO)
    WHERE ID_VETERINARIO IS NOT NULL;

-- TB_ARKIVE_USUARIO: Credenciais de acesso de responsaveis e veterinarios.
-- TB_ARKIVE_USUARIO.ID_USUARIO: Identificador unico do usuario.
-- TB_ARKIVE_USUARIO.TP_USUARIO: Tipo de usuario: RESPONSAVEL ou VETERINARIO.
-- TB_ARKIVE_USUARIO.ID_RESPONSAVEL: Responsavel associado ao usuario, quando aplicavel.
-- TB_ARKIVE_USUARIO.ID_VETERINARIO: Veterinario associado ao usuario, quando aplicavel.
-- TB_ARKIVE_USUARIO.DS_LOGIN: Login do usuario.
-- TB_ARKIVE_USUARIO.DS_SENHA_HASH: Hash da senha do usuario.
-- TB_ARKIVE_USUARIO.DT_CADASTRO: Data de criacao da conta.
-- TB_ARKIVE_USUARIO.ST_ATIVO: Indica exclusao logica: S = ativo, N = inativo.

