-- TB_ARKIVE_RESPONSAVEL_ANIMAL.DT_FIM: Data de fim do vinculo, quando encerrado.
-- TB_ARKIVE_RESPONSAVEL_ANIMAL.ST_PRINCIPAL: Indica se e o responsavel principal: S ou N.
-- TB_ARKIVE_RESPONSAVEL_ANIMAL.ST_ATIVO: Indica se o vinculo esta ativo: S ou N.

