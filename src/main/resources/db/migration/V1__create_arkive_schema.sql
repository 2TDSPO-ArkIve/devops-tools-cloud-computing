-- TB_ARKIVE_CONSULTA.DT_HORA: Data e hora da consulta.
-- TB_ARKIVE_CONSULTA.TP_MODALIDADE: Modalidade da consulta: Presencial ou Remota.
-- TB_ARKIVE_CONSULTA.DS_MOTIVO: Motivo principal da consulta.
-- TB_ARKIVE_CONSULTA.DS_SINTOMAS: Sintomas relatados pelo responsavel ou observados pelo veterinario.
-- TB_ARKIVE_CONSULTA.DS_OBSERVACAO: Observacoes clinicas gerais.
-- TB_ARKIVE_CONSULTA.KG_PESO: Peso registrado durante a consulta.
