-- SQL Server does not support function-based indexes like Oracle's NVL(ID_RACA, 0).
-- A persisted computed column reproduces the same "treat NULL race as 0" uniqueness rule.
ALTER TABLE TB_ARKIVE_PREDISPOSICAO ADD ID_RACA_COALESCE AS (ISNULL(ID_RACA, 0)) PERSISTED;

CREATE UNIQUE INDEX UX_ARKIVE_PREDISPOSICAO
    ON TB_ARKIVE_PREDISPOSICAO (ID_ESPECIE, ID_RACA_COALESCE, ID_DOENCA);

